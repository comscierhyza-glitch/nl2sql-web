                The system tokenizes the sentence, extracts keywords,
                parses the input and generates an SQL query.
            </p>

        </div>

    </div>


    <div class="guide-step">

        <div class="guide-number">3</div>

        <div>

            <h3>Review Generated SQL</h3>

            <p>
                Verify the generated SQL query before using it in your database.
            </p>

            <pre>
SELECT *
FROM students
WHERE age > 18;
</pre>

        </div>

    </div>


    <div class="guide-step">

        <div class="guide-number">4</div>

        <div>

            <h3>Copy or Download</h3>

            <p>
