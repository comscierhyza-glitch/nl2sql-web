<div class="guide-container">

    <div class="guide-step">

        <div class="guide-number">1</div>

        <div>

            <h3>Enter Natural Language</h3>

            <p>
                Type an English sentence describing the SQL query you want to generate.
            </p>

            <pre>Show all students where age is greater than 18</pre>

        </div>

    </div>


    <div class="guide-step">

        <div class="guide-number">2</div>

        <div>

            <h3>Click Generate SQL</h3>

