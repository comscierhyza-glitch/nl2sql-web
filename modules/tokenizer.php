<?php

$stopwords = require __DIR__ . '/../rules/stopwords.php';

function tokenize($input)
{
    global $stopwords;

    /*
    |--------------------------------------------------------------------------
    | Normalize Input
    |--------------------------------------------------------------------------
    */

    $input = strtolower(trim($input));

    $input = preg_replace('/\s+/', ' ', $input);

    /*
    |--------------------------------------------------------------------------
    | Remove unnecessary punctuation
    |--------------------------------------------------------------------------
    | Keep:
    | > < = ! . _ - ' "
    */

    $input = preg_replace(
        '/[,\;\(\)\{\}\[\]]/',
        ' ',
        $input
    );

    /*
    |--------------------------------------------------------------------------
    | Tokenize
    |--------------------------------------------------------------------------
    */

    preg_match_all(
        "/>=|<=|<>|!=|=|>|<|\*|'[^']*'|\"[^\"]*\"|-?\d+\.\d+|-?\d+|[a-zA-Z0-9_.-]+|[a-zA-Z]+(?:'[a-zA-Z]+)?/",
        $input,
        $matches
    );

    $tokens = array_map('trim', $matches[0]);

    /*
    |--------------------------------------------------------------------------
    | Remove Stop Words
    |--------------------------------------------------------------------------
    */

    $tokens = array_filter($tokens, function ($token) use ($stopwords) {

        return !in_array(
            strtolower($token),
            $stopwords
        );
    });

    /*
    |--------------------------------------------------------------------------
    | Remove Empty Tokens
    |--------------------------------------------------------------------------
    */

    $tokens = array_filter($tokens);

    /*
    |--------------------------------------------------------------------------
    | Return Tokens
    |--------------------------------------------------------------------------
    */

    return array_values($tokens);
}
